#!/usr/bin/env python3
"""WCAG 2.x contrast check for every pair in tokens.json, in every theme.

Usage: python3 -I replica/design/tools/contrast.py [tokens.json] [--md report.md]
Exit code 1 if any pair fails its threshold:
  body  -> 4.5:1 (normal text)
  large -> 3:1   (text >= 18.66px bold / 24px)
  ui    -> 3:1   (input borders, focus rings, graphical objects; WCAG 1.4.11)
Colors with alpha are composited over the pair's background.
"""
import json
import sys
from pathlib import Path

THRESHOLD = {"body": 4.5, "large": 3.0, "ui": 3.0}


def parse(hex_):
    h = hex_.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
    return r, g, b, a


def over(fg, bg):
    r, g, b, a = fg
    br, bgg, bb, _ = bg
    return (r * a + br * (1 - a), g * a + bgg * (1 - a), b * a + bb * (1 - a), 1.0)


def lum(c):
    def ch(v):
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b, _ = c
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def ratio(fg, bg):
    l1, l2 = sorted((lum(fg), lum(bg)), reverse=True)
    return (l1 + 0.05) / (l2 + 0.05)


def main():
    args = sys.argv[1:]
    md = None
    if "--md" in args:
        i = args.index("--md")
        md = args[i + 1]
        del args[i:i + 2]
    path = Path(args[0]) if args else Path(__file__).resolve().parents[1] / "tokens.json"
    tokens = json.loads(path.read_text())
    rows, failures = [], 0
    for theme, colors in tokens["color"].items():
        for p in tokens["pairs"]:
            bg = parse(colors[p["bg"]])
            fg = over(parse(colors[p["fg"]]), bg)
            r = ratio(fg, bg)
            need = THRESHOLD[p["use"]]
            ok = r >= need
            failures += not ok
            rows.append((theme, p["fg"], p["bg"], p["use"], r, need, ok))
    width = max(len(f"{r[1]} on {r[2]}") for r in rows)
    for theme, fg, bg, use, r, need, ok in rows:
        print(f"{theme:5}  {f'{fg} on {bg}':{width}}  {use:5}  {r:5.2f}:1  need {need}  {'ok' if ok else 'FAIL'}")
    print(f"\n{len(rows)} pairs, {failures} failures")
    if md:
        lines = ["# Contrast report", "", f"Generated by `tools/contrast.py` from `tokens.json`. {len(rows)} pairs, **{failures} failures**.", "",
                 "| theme | foreground | background | use | ratio | needed | result |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for theme, fg, bg, use, r, need, ok in rows:
            lines.append(f"| {theme} | `{fg}` | `{bg}` | {use} | {r:.2f}:1 | {need}:1 | {'pass' if ok else '**FAIL**'} |")
        Path(md).write_text("\n".join(lines) + "\n")
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
